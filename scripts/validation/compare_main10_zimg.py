#!/usr/bin/env python3
"""Compare final iOS Main10 output using independent zimg on BOTH sides.

Input references are generated by generate_zimg_references.py. FFmpeg only
handles video decompression, RGB scaling, LUTs, and container inspection;
legacy swscale never performs a YUV->RGB conversion for this comparison.
"""
import argparse
import json
from pathlib import Path
import subprocess
from PIL import Image
import validate_media as v

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('original',type=Path);p.add_argument('video',type=Path)
p.add_argument('--reference-directory',type=Path,required=True)
p.add_argument('--output',type=Path,required=True);a=p.parse_args()
refs=a.reference_directory.resolve();out=a.output.resolve();out.mkdir(parents=True,exist_ok=True)
video=a.video.resolve();probe=v.probe(video);stream=next(s for s in probe['streams']if s['codec_type']=='video')
if stream['pix_fmt']!='yuv420p10le':p.error('This validation requires actual10bit420output.')
w,h=stream['width'],stream['height'];raw=out/'main10-samples.yuv';commands=[]
def run(args):commands.append(args);subprocess.run(args,check=True)
run(['ffmpeg','-hide_banner','-loglevel','error','-threads','2','-i',str(video),'-vf','select=eq(n\\,0)+eq(n\\,60)+eq(n\\,150)','-fps_mode','passthrough','-frames:v','3','-pix_fmt','yuv420p10le','-f','rawvideo','-y',str(raw)])
manifest={'video':str(video),'probe':probe,'reference_manifest':str(refs/'reference-manifest.json'),
          'method':'Both originalsource andactualMain10output useindependentlibzimgmatrix/rangeRGBconversion; sourcefull709YUV42210,outputlimited709YUV42010; sameencodedtransfer/primaries, no gamma reinterpretation; referenceSonyprimary+M3147%normalopacity. RGB8metrics960x540.',
          'frames':[]}
with raw.open('rb')as data:
 for frame in v.FRAMES:
  yuv=out/f'actual_f{frame}.yuv';floating=out/f'actual_f{frame}.gbrpf32le';image=out/f'actual_f{frame}.png'
  chunk=data.read(w*h*3)
  if len(chunk)!=w*h*3:raise ValueError('Decoded samples incomplete')
  yuv.write_bytes(chunk)
  run([str(refs/'zimg-reference'),str(yuv),str(floating),str(w),str(h),'10','1','1','0','1'])
  run(['ffmpeg','-hide_banner','-loglevel','error','-f','rawvideo','-pixel_format','gbrpf32le','-video_size',f'{w}x{h}','-i',str(floating),'-vf','scale=960:540:flags=lanczos,format=rgb24','-frames:v','1','-y',str(image)])
  base=Image.open(refs/f'endpoint_bt709_primary_f{frame}.png').convert('RGB')
  creative=Image.open(refs/f'endpoint_bt709_M31 - Rec.709_f{frame}.png').convert('RGB')
  expected=Image.blend(base,creative,.47)
  result={'frame':frame,**v.metrics(Image.open(image),expected)};manifest['frames'].append(result)
  yuv.unlink();floating.unlink();print(result,flush=True)
raw.unlink();manifest['audio']=v.audio_comparison(v.read_audio(a.original),v.read_audio(video))
v.run(['ffmpeg','-hide_banner','-loglevel','error','-xerror','-threads','2','-i',str(video),'-map','0:v:0','-map','0:a?','-f','null','-'])
manifest['full_decode_passed']=True;manifest['commands']=commands+v.COMMANDS
(out/'ios-main10-zimg-validation.json').write_text(json.dumps(manifest,indent=2)+'\n');print(out/'ios-main10-zimg-validation.json')
